CREATE TABLE sucursal (
    id_sucursal   SMALLINT     GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR(80)  NOT NULL,
    direccion     VARCHAR(120) NOT NULL,
    municipio     VARCHAR(60)  NOT NULL,
    hora_apertura TIME         NOT NULL,
    hora_cierre   TIME         NOT NULL,

    CONSTRAINT pk_sucursal PRIMARY KEY (id_sucursal),
    CONSTRAINT uq_sucursal_nombre UNIQUE (nombre),
    CONSTRAINT ck_sucursal_horario CHECK (hora_cierre > hora_apertura)
);


CREATE TABLE empresa_seguridad (
    nit    VARCHAR(11)  NOT NULL,
    nombre VARCHAR(100) NOT NULL,

    CONSTRAINT pk_empresa_seguridad PRIMARY KEY (nit),
    CONSTRAINT uq_empresa_seguridad_nombre UNIQUE (nombre),
    CONSTRAINT ck_empresa_seguridad_nit CHECK (nit ~ '^[0-9]{9}-[0-9]$')
);


CREATE TABLE salario_minimo (
    anio          SMALLINT      NOT NULL,
    valor_mensual NUMERIC(12,2) NOT NULL,

    CONSTRAINT pk_salario_minimo PRIMARY KEY (anio),
    CONSTRAINT ck_salario_minimo_anio  CHECK (anio >= 2000),
    CONSTRAINT ck_salario_minimo_valor CHECK (valor_mensual > 0)
);


CREATE TABLE empleado (
    cedula        VARCHAR(10) NOT NULL,
    id_sucursal   SMALLINT    NOT NULL,
    tipo_empleado VARCHAR(20) NOT NULL,
    tipo_contrato VARCHAR(12) NOT NULL,
    fecha_ingreso DATE        NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_empleado PRIMARY KEY (cedula),
    CONSTRAINT uq_empleado_cedula_tipo UNIQUE (cedula, tipo_empleado),
    CONSTRAINT fk_empleado_persona FOREIGN KEY (cedula)
        REFERENCES persona (cedula) ON DELETE RESTRICT,
 
    CONSTRAINT fk_empleado_sucursal FOREIGN KEY (id_sucursal)
        REFERENCES sucursal (id_sucursal) ON DELETE RESTRICT,
    CONSTRAINT ck_empleado_tipo
        CHECK (tipo_empleado IN ('CAJERO', 'SERVICIOS_GENERALES', 'VIGILANTE')),
    CONSTRAINT ck_empleado_contrato
        CHECK (tipo_contrato IN ('INDEFINIDO', 'FIJO', 'TERCERIZADO')),

    CONSTRAINT ck_empleado_vigilante_tercerizado
        CHECK ((tipo_empleado = 'VIGILANTE') = (tipo_contrato = 'TERCERIZADO')),
    CONSTRAINT ck_empleado_fecha_ingreso CHECK (fecha_ingreso <= CURRENT_DATE)
);


CREATE TABLE cajero (
    cedula        VARCHAR(10)   NOT NULL,
    tipo_empleado VARCHAR(20)   NOT NULL DEFAULT 'CAJERO',
    bono_mensual  NUMERIC(12,2) NOT NULL DEFAULT 0,

    CONSTRAINT pk_cajero PRIMARY KEY (cedula),
    CONSTRAINT ck_cajero_tipo  CHECK (tipo_empleado = 'CAJERO'),
    CONSTRAINT ck_cajero_bono  CHECK (bono_mensual >= 0),
    CONSTRAINT fk_cajero_empleado FOREIGN KEY (cedula, tipo_empleado)
        REFERENCES empleado (cedula, tipo_empleado) ON DELETE CASCADE
);


CREATE TABLE servicios_generales (
    cedula        VARCHAR(10) NOT NULL,
    tipo_empleado VARCHAR(20) NOT NULL DEFAULT 'SERVICIOS_GENERALES',

    CONSTRAINT pk_servicios_generales PRIMARY KEY (cedula),
    CONSTRAINT ck_servgen_tipo CHECK (tipo_empleado = 'SERVICIOS_GENERALES'),
    CONSTRAINT fk_servgen_empleado FOREIGN KEY (cedula, tipo_empleado)
        REFERENCES empleado (cedula, tipo_empleado) ON DELETE CASCADE
);


CREATE TABLE vigilante_contratista (
    cedula        VARCHAR(10)  NOT NULL,
    tipo_empleado VARCHAR(20)  NOT NULL DEFAULT 'VIGILANTE',
    nit_empresa   VARCHAR(11)  NOT NULL,
    valor_hora    NUMERIC(10,2) NOT NULL,

    CONSTRAINT pk_vigilante_contratista PRIMARY KEY (cedula),
    CONSTRAINT ck_vigilante_tipo CHECK (tipo_empleado = 'VIGILANTE'),
    CONSTRAINT ck_vigilante_valor_hora CHECK (valor_hora > 0),
    CONSTRAINT fk_vigilante_empleado FOREIGN KEY (cedula, tipo_empleado)
        REFERENCES empleado (cedula, tipo_empleado) ON DELETE CASCADE,
    CONSTRAINT fk_vigilante_empresa FOREIGN KEY (nit_empresa)
        REFERENCES empresa_seguridad (nit) ON DELETE RESTRICT
);


