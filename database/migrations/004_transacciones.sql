CREATE TABLE tipo_transaccion (
    codigo        VARCHAR(15)  NOT NULL,
    descripcion   VARCHAR(100) NOT NULL,
    tasa_impuesto NUMERIC(6,5) NOT NULL DEFAULT 0,

    CONSTRAINT pk_tipo_transaccion PRIMARY KEY (codigo),
    CONSTRAINT ck_tipo_transaccion_tasa CHECK (tasa_impuesto >= 0 AND tasa_impuesto < 1)
);


CREATE TABLE transaccion (
    id_transaccion   BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    tipo_transaccion VARCHAR(15)   NOT NULL,
    fecha_hora       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    monto            NUMERIC(14,2) NOT NULL,
    cuenta_origen    VARCHAR(10),
    cuenta_destino   VARCHAR(10),
    cedula_cajero    VARCHAR(10)   NOT NULL,
    id_sucursal      SMALLINT      NOT NULL,

    CONSTRAINT pk_transaccion PRIMARY KEY (id_transaccion),
    CONSTRAINT fk_trans_tipo FOREIGN KEY (tipo_transaccion)
        REFERENCES tipo_transaccion (codigo) ON DELETE RESTRICT,
    CONSTRAINT fk_trans_origen FOREIGN KEY (cuenta_origen)
        REFERENCES cuenta (numero_cuenta) ON DELETE RESTRICT,
    CONSTRAINT fk_trans_destino FOREIGN KEY (cuenta_destino)
        REFERENCES cuenta (numero_cuenta) ON DELETE RESTRICT,
   
    CONSTRAINT fk_trans_cajero FOREIGN KEY (cedula_cajero)
        REFERENCES cajero (cedula) ON DELETE RESTRICT,
    CONSTRAINT fk_trans_sucursal FOREIGN KEY (id_sucursal)
        REFERENCES sucursal (id_sucursal) ON DELETE RESTRICT,
    CONSTRAINT ck_trans_monto_positivo CHECK (monto > 0),
    CONSTRAINT ck_trans_cuentas_segun_tipo CHECK (
        (tipo_transaccion = 'DEPOSITO'
            AND cuenta_origen IS NULL AND cuenta_destino IS NOT NULL)
     OR (tipo_transaccion = 'RETIRO'
            AND cuenta_origen IS NOT NULL AND cuenta_destino IS NULL)
     OR (tipo_transaccion = 'TRANSFERENCIA'
            AND cuenta_origen IS NOT NULL AND cuenta_destino IS NOT NULL
            AND cuenta_origen <> cuenta_destino)
    )
);


CREATE TABLE impuesto_transaccion (
    id_transaccion BIGINT        NOT NULL,
    tasa_aplicada  NUMERIC(6,5)  NOT NULL,
    valor_impuesto NUMERIC(14,2) NOT NULL,

    CONSTRAINT pk_impuesto_transaccion PRIMARY KEY (id_transaccion),
    CONSTRAINT fk_impuesto_transaccion FOREIGN KEY (id_transaccion)
        REFERENCES transaccion (id_transaccion) ON DELETE CASCADE,
    CONSTRAINT ck_impuesto_tasa  CHECK (tasa_aplicada > 0 AND tasa_aplicada < 1),
    CONSTRAINT ck_impuesto_valor CHECK (valor_impuesto > 0)
);

